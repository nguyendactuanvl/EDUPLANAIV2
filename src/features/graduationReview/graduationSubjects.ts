export type SubjectCategory = "toan" | "khtn" | "khxh" | "tieng_anh" | "ngu_van" | "tin_hoc";

export function getSubjectCategory(subjectId: string): SubjectCategory {
  if (subjectId === "toan") return "toan";
  if (["vat_ly", "hoa_hoc", "sinh_hoc"].includes(subjectId)) return "khtn";
  if (["lich_su", "dia_li", "gd_ktpl"].includes(subjectId)) return "khxh";
  if (subjectId === "tieng_anh") return "tieng_anh";
  if (subjectId === "ngu_van") return "ngu_van";
  if (subjectId === "tin_hoc") return "tin_hoc";
  return "khtn";
}

